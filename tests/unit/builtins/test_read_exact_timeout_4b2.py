class TestRiderMustHoldControls:
    def test_count_satisfied_before_the_deadline(self, tmp_path):
        assert _assert_parity(
            lambda arm: _no_eof_script(tmp_path, arm, f"-t {TIMEOUT} -N 3",
                                       b"abc"),
            tmp_path) == "rc=0 bytes=616263"

    def test_eof_before_the_count_without_t(self, tmp_path):
        assert _assert_parity(
            lambda arm: _eof_script(tmp_path, arm, "-N 3", b"ab"),
            tmp_path) == "rc=1 bytes=6162"

    def test_eof_before_the_count_with_t(self, tmp_path):
        assert _assert_parity(
            lambda arm: _eof_script(tmp_path, arm, f"-t {TIMEOUT} -N 3", b"ab"),
            tmp_path) == "rc=1 bytes=6162"

    def test_zero_count_with_t_returns_at_once(self, tmp_path):
        assert _assert_parity(
            lambda arm: _no_eof_script(tmp_path, arm, f"-t {TIMEOUT} -N 0"),
            tmp_path) == "rc=0 bytes="

    def test_poll_with_data_ready_assigns_nothing(self, tmp_path):
        # `-t 0` is a non-consuming poll and precedes the -N branch: readable
        # means rc 0 with the variable untouched.
        assert _assert_parity(
            lambda arm: _no_eof_script(tmp_path, arm, "-t 0 -N 3", b"abc"),
            tmp_path) == "rc=0 bytes="

    def test_poll_with_no_data_reports_would_block(self, tmp_path):
        assert _assert_parity(
            lambda arm: _no_eof_script(tmp_path, arm, "-t 0 -N 3"),
            tmp_path) == "rc=1 bytes="

    def test_delimiter_is_ignored_under_exact_count(self, tmp_path):
        assert _assert_parity(
            lambda arm: _no_eof_script(tmp_path, arm, f"-t {TIMEOUT} -d : -N 3",
                                       b"a:bc"),
            tmp_path) == "rc=0 bytes=613a62"

    def test_raw_mode_keeps_the_backslash(self, tmp_path):
        assert _assert_parity(
            lambda arm: _eof_script(tmp_path, arm, "-r -N 3", b"a\\b"),
            tmp_path) == "rc=0 bytes=615c62"

    def test_multibyte_completed_before_the_deadline(self, tmp_path):
        assert _assert_parity(
            lambda arm: _no_eof_script(tmp_path, arm, f"-t {TIMEOUT} -N 2",
                                       b"a\xc3\xa9"),
            tmp_path) == "rc=0 bytes=61c3a9"

    def test_multibyte_truncated_at_eof_without_t(self, tmp_path):
        assert _assert_parity(
            lambda arm: _eof_script(tmp_path, arm, "-N 2", b"a\xc3"),
            tmp_path) == "rc=0 bytes=61c3"


